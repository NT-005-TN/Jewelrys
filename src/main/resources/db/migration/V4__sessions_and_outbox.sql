CREATE TABLE email_outbox (
 id BIGSERIAL PRIMARY KEY, recipient VARCHAR(255) NOT NULL, subject TEXT NOT NULL,
 body TEXT NOT NULL, attempts INTEGER NOT NULL DEFAULT 0,
 next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 sent_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX email_outbox_pending ON email_outbox(next_attempt_at) WHERE sent_at IS NULL;
